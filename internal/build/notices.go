// Identify disposable generated output and direct edits back to authoritative inputs.

package build

const generatedNotice = "Generated by Code Rules. Do not edit this file manually."
const regenerationNotice = "Edit source rules or configuration, then run `code-rules project build`. Use `code-rules project sync` to fetch libraries and regenerate. Run project commands from the project root."

// generatedMarkdown makes ownership visible in both raw Markdown and rendered documents.
func generatedMarkdown(text string) string {
	return "> **" + generatedNotice + "**\n> " + regenerationNotice + "\n\n" + text
}
